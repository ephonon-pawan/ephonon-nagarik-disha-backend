CREATE TABLE IF NOT EXISTS citizen_groups (
 id VARCHAR(64) PRIMARY KEY, name VARCHAR(160) NOT NULL, description TEXT NOT NULL,
 icon VARCHAR(64) NOT NULL, sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sectors (
 id VARCHAR(64) PRIMARY KEY, name VARCHAR(160) NOT NULL, description TEXT NOT NULL,
 icon VARCHAR(64) NOT NULL, color VARCHAR(7) NOT NULL, action VARCHAR(160) NOT NULL,
 keywords TEXT NOT NULL, sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sector_groups (
 sector_id VARCHAR(64) NOT NULL, group_id VARCHAR(64) NOT NULL,
 PRIMARY KEY(sector_id, group_id),
 FOREIGN KEY(sector_id) REFERENCES sectors(id) ON DELETE CASCADE,
 FOREIGN KEY(group_id) REFERENCES citizen_groups(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS resources (
 id VARCHAR(64) PRIMARY KEY, sector_id VARCHAR(64) NOT NULL,
 name VARCHAR(160) NOT NULL, description TEXT NOT NULL, eligibility TEXT NOT NULL,
 documents JSON NOT NULL, url VARCHAR(2048) NOT NULL, source_url VARCHAR(2048) NULL,
 last_verified DATE NULL, sort_order INT NOT NULL DEFAULT 0,
 FOREIGN KEY(sector_id) REFERENCES sectors(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS helpline_sections (
 id VARCHAR(64) PRIMARY KEY, title VARCHAR(160) NOT NULL, sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS helplines (
 id VARCHAR(64) PRIMARY KEY, section_id VARCHAR(64) NOT NULL,
 name VARCHAR(160) NOT NULL, description TEXT NOT NULL, number VARCHAR(32) NOT NULL,
 region VARCHAR(160) NOT NULL DEFAULT 'India', source_url VARCHAR(2048) NULL,
 last_verified DATE NULL, emergency_label VARCHAR(100) NULL, emergency_order INT NULL,
 sort_order INT NOT NULL DEFAULT 0,
 FOREIGN KEY(section_id) REFERENCES helpline_sections(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS admins (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(200) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS admin_sessions (
 token_hash CHAR(64) PRIMARY KEY,
 admin_id BIGINT UNSIGNED NOT NULL,
 csrf_token CHAR(64) NOT NULL,
 expires_at DATETIME NOT NULL,
 INDEX(expires_at),
 FOREIGN KEY(admin_id) REFERENCES admins(id) ON DELETE CASCADE
) ENGINE=InnoDB;
